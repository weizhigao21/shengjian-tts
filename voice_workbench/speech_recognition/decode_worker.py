"""Qt decoding runs on a child's main thread; the HTTP service stays Qt-free."""
import argparse
from array import array
import math
from pathlib import Path
import sys
import wave


def main(argv=None):
    parser = argparse.ArgumentParser(description="识别音频解码")
    parser.add_argument("source", type=Path)
    parser.add_argument("target", type=Path)
    args = parser.parse_args(argv)
    from PyQt6.QtCore import QCoreApplication, QTimer, QUrl
    from PyQt6.QtMultimedia import QAudioDecoder, QAudioFormat

    app = QCoreApplication([])
    decoder = QAudioDecoder()
    frames = 0
    sample_format = None
    failure = None
    # The destination is generated by the service, never the user's input file.
    with wave.open(str(args.target), "wb") as output:
        output.setparams((1, 2, 16000, 0, "NONE", "not compressed"))

        def fail(message):
            nonlocal failure
            failure = str(message)
            decoder.stop()
            app.exit(1)

        def read_buffer():
            nonlocal frames, sample_format
            try:
                buffer = decoder.read()
                if not buffer.isValid():
                    return
                fmt = buffer.format()
                actual = (fmt.sampleRate(), fmt.channelCount(), fmt.sampleFormat())
                if sample_format is not None and sample_format != actual:
                    raise ValueError("音频中途改变了采样格式，请转换为 PCM WAV 后重试")
                if sample_format is None:
                    sample_format = actual
                    output.setparams((fmt.channelCount(), 2, fmt.sampleRate(), 0, "NONE", "not compressed"))
                # Let Qt decode at the source rate. Its resampler can stall on short,
                # gapless MP3 frames. The inference engine already resamples its input.
                raw = buffer.constData().asstring(buffer.byteCount())
                if fmt.sampleFormat() == QAudioFormat.SampleFormat.Float:
                    source = array('f'); source.frombytes(raw)
                    pcm = array('h', (min(32767, max(-32768, int(value * 32768))) if math.isfinite(value) else 0 for value in source))
                elif fmt.sampleFormat() == QAudioFormat.SampleFormat.Int32:
                    source = array('i'); source.frombytes(raw)
                    pcm = array('h', (value >> 16 for value in source))
                elif fmt.sampleFormat() == QAudioFormat.SampleFormat.UInt8:
                    pcm = array('h', ((value - 128) << 8 for value in raw))
                elif fmt.sampleFormat() == QAudioFormat.SampleFormat.Int16:
                    pcm = array('h'); pcm.frombytes(raw)
                else:
                    raise ValueError("无法识别解码后的采样格式")
                if sys.byteorder != 'little':
                    pcm.byteswap()
                output.writeframesraw(pcm.tobytes())
                frames += buffer.frameCount()
            except Exception as exc:
                fail(exc)

        decoder.bufferReady.connect(read_buffer)
        decoder.error.connect(lambda _: fail(decoder.errorString()))
        decoder.finished.connect(lambda: app.exit(0) if frames else fail("音频没有可读取的声音数据"))
        QTimer.singleShot(115000, lambda: fail("音频解码超时，请使用较短的录音重试"))
        def start():
            decoder.setSource(QUrl.fromLocalFile(str(args.source.resolve())))
            decoder.start()
        # Synchronous format errors must be delivered after the event loop starts.
        QTimer.singleShot(0, start)
        code = app.exec()
    if code:
        args.target.unlink(missing_ok=True)
        print(failure or "音频解码失败", file=sys.stderr)
    raise SystemExit(code)
