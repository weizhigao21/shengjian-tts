"""Single-track audio editing page; processing and persistence live in its controller."""
from PyQt6.QtCore import Qt
from PyQt6.QtWidgets import (QComboBox, QDoubleSpinBox, QFormLayout, QHBoxLayout, QLineEdit,
                            QListWidget, QScrollArea, QSpinBox, QTextEdit, QVBoxLayout, QWidget)
from ...ui import button, label
from ..components.audio_selection import AudioSelection
from ..controllers.audio_editing import AudioEditController


class AudioEditPanel(QWidget):
    def __init__(self, owner):
        super().__init__()
        self.owner = owner
        self.controller = AudioEditController(owner, self)
        main = QHBoxLayout(self)
        main.setContentsMargins(18, 12, 18, 12)
        main.setSpacing(20)
        center = QWidget()
        center.setObjectName("audioEditContent")
        content = QVBoxLayout(center)
        content.setContentsMargins(0, 0, 8, 0)
        content.setSpacing(12)
        header = QHBoxLayout()
        header.addWidget(button("返回", owner.open_creation_home, "back", "ghost"))
        self.title = QLineEdit("未命名音频")
        self.title.setObjectName("documentTitle")
        self.title.setMaxLength(200)
        header.addWidget(self.title, 1)
        self.import_button = button("导入 WAV", self.controller.import_audio, "import")
        self.export_button = button("导出", self.controller.export, "export", "ghost")
        header.addWidget(self.import_button)
        header.addWidget(self.export_button)
        content.addLayout(header)
        recent = QHBoxLayout()
        recent.addWidget(label("编辑项目", "muted"))
        self.projects = QComboBox()
        self.projects.setMinimumContentsLength(10)
        self.projects.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
        self.projects.currentIndexChanged.connect(self.controller.open_selected_project)
        recent.addWidget(self.projects, 1)
        content.addLayout(recent)
        self.info = label("导入 PCM WAV，或从生成记录打开音频。", "hint")
        self.info.setWordWrap(True)
        content.addWidget(self.info)
        self.waveform = AudioSelection()
        self.waveform.selection_changed.connect(self.controller.set_selection)
        content.addWidget(self.waveform)
        selection = QHBoxLayout()
        selection.addWidget(label("选区（秒）", "muted"))
        self.start, self.end = self.seconds(0), self.seconds(0)
        self.start.valueChanged.connect(self.controller.selection_changed)
        self.end.valueChanged.connect(self.controller.selection_changed)
        selection.addWidget(self.start)
        selection.addWidget(label("—", "muted"))
        selection.addWidget(self.end)
        selection.addWidget(button("全选", self.controller.select_all, "audio", "ghost"))
        selection.addStretch()
        content.addLayout(selection)
        transport = QHBoxLayout()
        self.preview_button = button("试听选区", self.controller.preview_selection, "play")
        self.original_button = button("原音频", self.controller.preview_original, "play", "ghost")
        self.stop_button = button("停止", self.controller.stop, "stop", "ghost")
        self.undo_button = button("返回上个版本", self.controller.undo, "back", "ghost")
        for control in (self.preview_button, self.original_button, self.stop_button, self.undo_button):
            transport.addWidget(control)
        transport.addStretch()
        self.clock = label("00:00 / 00:00", "muted")
        transport.addWidget(self.clock)
        content.addLayout(transport)
        content.addWidget(label("当前音频原文（手动填写）", "muted"))
        self.original_text = QTextEdit()
        self.original_text.setPlaceholderText("准确的原文有助于台词修改；选择一段音频时填写该段的原文。")
        self.original_text.setMaximumHeight(88)
        content.addWidget(self.original_text)
        content.addWidget(label("修改后的台词", "muted"))
        self.target_text = QTextEdit()
        self.target_text.setPlaceholderText("填写希望这段音频说出的新台词。")
        self.target_text.setMinimumHeight(90)
        self.target_text.setMaximumHeight(130)
        content.addWidget(self.target_text, 1)
        content.addWidget(button("保存名称与台词", self.controller.save, "check", "ghost"), 0, Qt.AlignmentFlag.AlignLeft)
        content.addWidget(label("版本记录 · 点击切换，完成的版本都可以试听和导出", "muted"))
        self.history = QListWidget()
        self.history.setMinimumHeight(88)
        self.history.setMaximumHeight(130)
        self.history.currentRowChanged.connect(self.controller.choose_version)
        content.addWidget(self.history)
        self.status = label("原音频会保留，每次处理创建一个新版本。", "hint")
        self.status.setWordWrap(True)
        content.addWidget(self.status)
        content_scroll = QScrollArea()
        content_scroll.setWidgetResizable(True)
        content_scroll.setFrameShape(QScrollArea.Shape.NoFrame)
        content_scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        content_scroll.setWidget(center)
        main.addWidget(content_scroll, 1)

        scroll = QScrollArea()
        scroll.setFixedWidth(300)
        scroll.setWidgetResizable(True)
        scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        inspector = QWidget()
        inspector.setObjectName("inspectorBody")
        side = QVBoxLayout(inspector)
        side.setContentsMargins(12, 4, 12, 12)
        side.setSpacing(12)
        side.addWidget(label("基础编辑", "section"))
        form = QFormLayout()
        self.gain = self.seconds(0, -36, 12)
        self.gain.setSuffix(" dB")
        self.fade_in, self.fade_out = self.seconds(0, 0, 10), self.seconds(0, 0, 10)
        self.fade_in.setSuffix(" 秒")
        self.fade_out.setSuffix(" 秒")
        form.addRow("音量", self.gain)
        form.addRow("淡入", self.fade_in)
        form.addRow("淡出", self.fade_out)
        side.addLayout(form)
        self.render_button = button("保留选区并应用调整", lambda: self.controller.process("render"), "audio", "primary")
        self.append_button = button("末尾拼接 WAV", self.controller.append_audio, "plus")
        side.addWidget(self.render_button)
        side.addWidget(self.append_button)
        side.addSpacing(10)
        side.addWidget(label("AI 编辑 · Vevo2（实验）", "section"))
        self.models = QComboBox()
        self.models.setMinimumContentsLength(10)
        self.models.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
        self.models.currentIndexChanged.connect(self.controller.update_actions)
        side.addWidget(self.models)
        side.addWidget(button("导入 Vevo2 GGUF", self.controller.import_model, "folder", "ghost"))
        side.addWidget(button("下载模型 / 管理引擎", lambda: owner.set_page(3), "import", "ghost"))
        side.addWidget(label("目标音色", "muted"))
        self.reference = QComboBox()
        self.reference.setMinimumContentsLength(10)
        self.reference.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
        self.reference.currentIndexChanged.connect(self.controller.update_actions)
        side.addWidget(self.reference)
        side.addWidget(button("选择参考 WAV", self.controller.choose_reference, "voices", "ghost"))
        self.device = QComboBox()
        self.device.addItem("NVIDIA GPU · CUDA", "cuda")
        self.device.addItem("CPU", "cpu")
        form = QFormLayout()
        self.steps = QSpinBox()
        self.steps.setRange(1, 100)
        self.steps.setValue(32)
        self.seed = QLineEdit("-1")
        self.seed.setToolTip("-1 表示随机；也可填写 0–4294967295，实际种子保存到版本详情。")
        form.addRow("设备", self.device)
        form.addRow("推理步数", self.steps)
        form.addRow("随机种子", self.seed)
        side.addLayout(form)
        self.vc_button = button("更换音色", lambda: self.controller.process("vc"), "voices", "primary")
        self.edit_button = button("生成修改后的台词", lambda: self.controller.process("edit"), "retry", "primary")
        side.addWidget(self.vc_button)
        side.addWidget(self.edit_button)
        self.cancel_button = button("取消处理", self.controller.cancel, "close", "ghost")
        side.addWidget(self.cancel_button)
        self.ai_hint = label("AI 每次处理选区，最长 60 秒；建议先用短句试听。台词修改会重新合成选区，结果保存为独立版本。", "hint")
        self.ai_hint.setWordWrap(True)
        side.addWidget(self.ai_hint)
        license_note = label("Vevo2 权重许可：CC-BY-NC-ND-4.0", "muted")
        license_note.setWordWrap(True)
        license_note.setToolTip("官方模型：https://huggingface.co/RMSnow/Vevo2\n模型权重许可独立于声笺应用许可。")
        side.addWidget(license_note)
        side.addStretch()
        scroll.setWidget(inspector)
        main.addWidget(scroll)
        self.controller.connect()

    @staticmethod
    def seconds(value, minimum=0, maximum=1800):
        control = QDoubleSpinBox()
        control.setDecimals(3)
        control.setRange(minimum, maximum)
        control.setSingleStep(0.1)
        control.setValue(value)
        return control
